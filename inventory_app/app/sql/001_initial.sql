-- Explicit PostgreSQL migration. Text decimal/date values are preserved exactly.
CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS staff_accounts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL, google_sub TEXT UNIQUE,
 name TEXT NOT NULL DEFAULT '', role TEXT NOT NULL DEFAULT 'staff' CHECK(role IN ('admin','owner','staff')),
 active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), version BIGINT NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL, last_login TEXT);
CREATE TABLE IF NOT EXISTS account_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES staff_accounts(id) DEFERRABLE INITIALLY IMMEDIATE,
 actor TEXT NOT NULL, action TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS products(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
 category TEXT NOT NULL DEFAULT '', supplier TEXT NOT NULL DEFAULT '', unit TEXT NOT NULL,
 price TEXT, minimum TEXT, specification TEXT NOT NULL DEFAULT '',
 conversions TEXT NOT NULL DEFAULT '{}', image TEXT, version BIGINT NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS batches(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 quantity TEXT, cost TEXT, received_on TEXT, expires_on TEXT,
 saleable BIGINT NOT NULL DEFAULT 0, version BIGINT NOT NULL DEFAULT 1, source TEXT);
CREATE TABLE IF NOT EXISTS movements(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 batch_id BIGINT REFERENCES batches(id) DEFERRABLE INITIALLY IMMEDIATE, kind TEXT NOT NULL, reason TEXT NOT NULL,
 before_value TEXT, after_value TEXT, actor TEXT NOT NULL, created_at TEXT NOT NULL,
 reversal_of BIGINT UNIQUE REFERENCES movements(id) DEFERRABLE INITIALLY IMMEDIATE);
CREATE TABLE IF NOT EXISTS requests(
 request_id TEXT PRIMARY KEY, payload_hash TEXT NOT NULL, result TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS imports(
 id TEXT PRIMARY KEY, fingerprint TEXT UNIQUE NOT NULL, status TEXT NOT NULL,
 preview TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS catalog_cards(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source TEXT NOT NULL UNIQUE, brand TEXT, name TEXT, specification TEXT,
 original_price TEXT, image TEXT, product_id BIGINT REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 pricing_mode TEXT NOT NULL DEFAULT 'fixed', independent BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS invoice_items(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source TEXT UNIQUE NOT NULL, category TEXT, code TEXT, name TEXT,
 price TEXT, unit TEXT, tax BIGINT, kind BIGINT,
 product_id BIGINT REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE, fixed BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS invoice_exports(
 id TEXT PRIMARY KEY, revision TEXT NOT NULL, filename TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS backup_runs(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT NOT NULL, path TEXT, error TEXT);
CREATE TABLE IF NOT EXISTS metadata(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS batches_product ON batches(product_id);
CREATE INDEX IF NOT EXISTS movements_product ON movements(product_id, id);

CREATE TABLE IF NOT EXISTS shop_products(
 product_id BIGINT PRIMARY KEY REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE, published BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS recipes(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT UNIQUE NOT NULL, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 icon TEXT NOT NULL DEFAULT '🍽️', theme TEXT NOT NULL DEFAULT 'noodles', tag TEXT NOT NULL DEFAULT '',
 notes TEXT NOT NULL DEFAULT '', steps TEXT NOT NULL DEFAULT '', published BIGINT NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 1, image TEXT);
CREATE TABLE IF NOT EXISTS recipe_items(
 recipe_id BIGINT NOT NULL REFERENCES recipes(id) DEFERRABLE INITIALLY IMMEDIATE, product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 quantity BIGINT NOT NULL CHECK(quantity>0 AND quantity<=99), optional BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(recipe_id,product_id));
CREATE TABLE IF NOT EXISTS customer_orders(
 id TEXT PRIMARY KEY, number TEXT NOT NULL UNIQUE, token_hash TEXT NOT NULL UNIQUE,
 client_hash TEXT NOT NULL, request_id TEXT NOT NULL UNIQUE, payload_hash TEXT NOT NULL,
 status TEXT NOT NULL, name TEXT NOT NULL, phone TEXT NOT NULL, pickup_date TEXT NOT NULL,
 pickup_slot TEXT NOT NULL, hold_until TEXT NOT NULL, total TEXT NOT NULL, snapshot TEXT NOT NULL,
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS order_items(
 order_id TEXT NOT NULL REFERENCES customer_orders(id) DEFERRABLE INITIALLY IMMEDIATE, product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 name TEXT NOT NULL, unit TEXT NOT NULL, quantity TEXT NOT NULL, price TEXT NOT NULL,
 PRIMARY KEY(order_id,product_id));
CREATE TABLE IF NOT EXISTS reservations(
 order_id TEXT NOT NULL REFERENCES customer_orders(id) DEFERRABLE INITIALLY IMMEDIATE, batch_id BIGINT NOT NULL REFERENCES batches(id) DEFERRABLE INITIALLY IMMEDIATE,
 quantity TEXT NOT NULL, PRIMARY KEY(order_id,batch_id));
CREATE TABLE IF NOT EXISTS order_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id TEXT NOT NULL REFERENCES customer_orders(id) DEFERRABLE INITIALLY IMMEDIATE,
 status TEXT NOT NULL, actor TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS shop_attempts(client_hash TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS order_status_index ON customer_orders(status,created_at);
CREATE INDEX IF NOT EXISTS reservation_batch_index ON reservations(batch_id);
CREATE INDEX IF NOT EXISTS attempts_index ON shop_attempts(client_hash,created_at);

CREATE UNIQUE INDEX IF NOT EXISTS staff_email_lower ON staff_accounts(lower(email));
