CREATE TABLE IF NOT EXISTS daily_sales(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sold_on TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL CHECK(status IN ('posted','void')), created_at TEXT NOT NULL, actor TEXT NOT NULL,
 void_reason TEXT, voided_at TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS daily_sales_one_posted ON daily_sales(sold_on) WHERE status='posted';
CREATE TABLE IF NOT EXISTS daily_sale_lines(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sheet_id BIGINT NOT NULL REFERENCES daily_sales(id) DEFERRABLE INITIALLY IMMEDIATE,
 product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
 name TEXT NOT NULL, code TEXT NOT NULL, unit TEXT NOT NULL, quantity TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS daily_sale_movements(
 line_id BIGINT NOT NULL REFERENCES daily_sale_lines(id) DEFERRABLE INITIALLY IMMEDIATE,
 movement_id BIGINT NOT NULL UNIQUE REFERENCES movements(id) DEFERRABLE INITIALLY IMMEDIATE);
